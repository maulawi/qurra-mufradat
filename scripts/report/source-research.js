"use strict";
/* Generates docs/content-source-research.md from data/sources.json so the written research can never drift from the
   licensing gate the validator enforces. `--check` fails if the document is stale. */
const fs = require("fs");
const path = require("path");
const ROOT = path.join(__dirname, "..", "..");
const OUT = path.join(ROOT, "docs", "content-source-research.md");
const sources = JSON.parse(fs.readFileSync(path.join(ROOT, "data", "sources.json"), "utf8")).sources;

const GROUPS = [
  ["Cleared and in use", s => s.gate.decision === "USE" && !/^QURRA_/.test(s.source_id), "Licence chain established; bundled with the recorded attribution."],
  ["QURRA-authored (owned)", s => s.gate.decision === "USE" && /^QURRA_/.test(s.source_id), "Written by QURRA editors; provisional content, never presented as reviewed."],
  ["Pending clarification", s => s.gate.decision === "PENDING_CLARIFICATION", "Permission may exist but depends on conditions or confirmation. Never bundled until resolved."],
  ["Reference only", s => s.gate.decision === "REFERENCE_ONLY", "May be consulted by a human; nothing is copied into QURRA data."],
  ["Rejected (do not use)", s => s.gate.decision === "DO_NOT_USE", "Known not to permit the use, or the licence/upstream is not established. Nothing imported."]
];
const cell = v => String(v === null || v === undefined ? "" : v).replace(/\|/g, "\|").replace(/\r?\n/g, " ");

function render() {
  const L = ["# Content source research (V1)", "",
    "> GENERATED by `node scripts/report/source-research.js` from `data/sources.json`. Do not edit by hand: edit the registry and re-run.", "",
    "Rule applied to every entry: a source is **not** imported merely because a paper says CC BY, a repository is public, a dataset is downloadable, another project uses it, or it is commonly used in research. Only a recorded, verifiable licence chain that permits redistribution inside a static, possibly commercial app clears a source (`CLEAR`). Anything else is held back and the reason is recorded.", "",
    "## Summary", "", "| Source | Type | Clearance | Decision |", "|---|---|---|---|"];
  sources.forEach(s => L.push(`| ${s.source_id} | ${s.type} | ${s.clearance} | ${s.gate.decision} |`));
  L.push("", "## What this means for V1 content", "",
    "| Need | Cleared source today | Status |", "|---|---|---|",
    "| Qur'an text, surah/ayah/juz metadata | Tanzil (CC BY 3.0, verbatim) | Complete |",
    "| English ayah translation | Pickthall 1930 (public domain) | 6,228 of 6,236 ayahs; 8 held back (merged verse numbers in the transcription) |",
    "| Malay ayah translation | none | Unavailable: Basmeih (JAKIM) is copyrighted; QuranEnc has no Malay edition; Indonesian is not Malay |",
    "| Word-by-word glosses (EN/BM) | QURRA's own, for the pilot only | Partial: pilot tokens only; QUL, quranwbw and others are not cleared |",
    "| Segmentation, lemma, POS | QURRA's own pilot | Partial: 91 tokens; QAC, MASAQ, QuranMorph, QAMAR, EQTB are not cleared |",
    "| Roots | none asserted at scale | Provisional/unresolved only; root protocol is not frozen |",
    "| Classical lexica | Lane (reference only) | Not imported |", "");
  for (const [title, test, blurb] of GROUPS) {
    const list = sources.filter(test);
    if (!list.length) continue;
    L.push(`## ${title}`, "", blurb, "");
    list.forEach(s => {
      L.push(`### ${s.source_id}: ${cell(s.name)}`, "",
        "| Field | Value |", "|---|---|",
        `| Type | ${cell(s.type)} |`, `| Version | ${cell(s.version)} |`, `| URL | ${cell(s.url)} |`,
        `| Licence | ${cell(s.licence)} |`, `| Licence URL | ${cell(s.licence_url)} |`, `| Clearance | **${s.clearance}** |`);
      for (const k of ["commercial_use", "redistribution", "static_bundling", "derivatives", "attribution", "modification", "third_party_material", "upstream", "decision", "reason"]) L.push(`| ${k.replace(/_/g, " ")} | ${cell(s.gate[k])} |`);
      L.push(`| Notes | ${cell(s.notes)} |`, "");
    });
  }
  return L.join("\n") + "\n";
}

if (require.main === module) {
  const text = render();
  if (process.argv.includes("--check")) {
    if (!fs.existsSync(OUT) || fs.readFileSync(OUT, "utf8") !== text) { console.error("STALE docs/content-source-research.md — run: node scripts/report/source-research.js"); process.exit(1); }
    console.log("source research: up to date");
  } else { fs.writeFileSync(OUT, text); console.log("wrote docs/content-source-research.md"); }
}
module.exports = { render };
